"""Rebuild the attributed human recordings used by Muslim Blast.

Letter-to-recording mapping: Wikiversity, Learn Arabic (Language Of Quran)/Alphabets.
Originals: Wikimedia Commons, each file's own attribution and CC BY-SA 4.0 licence.
Only format conversion is applied; speech is not generated or edited.
Requires Python 3 and ffmpeg. Run from the repository root.
"""
import hashlib
import json
import re
import subprocess
import tempfile
import time
import urllib.parse
import urllib.request
from pathlib import Path

FILES = [
    ('alif', 'Alif A.wav'), ('ba', 'Baaudio.wav'), ('ta', 'Taaudio.wav'),
    ('tsa', 'Thaaudio.wav'), ('jim', 'Jeemaudio.wav'), ('ha', 'Haaudio.wav'),
    ('kha', 'Khaaudio.wav'), ('dal', 'Dalaudio.wav'), ('dzal', 'Dzalaudio.wav'),
    ('ra', 'RAAUDIO.wav'), ('zay', 'ZaiAUDIO.wav'), ('sin', 'Senaudio.wav'),
    ('syin', 'Shenaudio.wav'), ('shad', 'Sadaudio.wav'), ('dhad', 'Ddadaudio.wav'),
    ('tha', 'Ttaaudio.wav'), ('zha', 'Dddaudio.wav'), ('ain', 'Aaaudio.wav'),
    ('ghain', 'Ghaudio.wav'), ('fa', 'Faaudio.wav'), ('qaf', 'Qafaudio.wav'),
    ('kaf', 'Kafaudio.wav'), ('lam', 'Lamudio.wav'), ('mim', 'Maudio.wav'),
    ('nun', 'Naudio.wav'), ('ha2', 'Haaaudio.wav'), ('waw', 'Wawaudio.wav'),
    ('ya', 'Yaaudio.wav'),
]
HEADERS = {'User-Agent': 'MuslimBlast/0.3 (educational audio source attribution)'}

def fetch(url):
    with urllib.request.urlopen(urllib.request.Request(url, headers=HEADERS), timeout=45) as response:
        return response.read()

def write_credits(manifest):
    encoded = json.dumps(manifest, ensure_ascii=False, indent=2)
    Path('public/assets/audio/hijaiyah/credits.json').write_text(encoded + '\n')
    Path('src/hijaiyah/audioSources.ts').write_text('// Generated by scripts/import-hijaiyah-audio.py. Keep audio attribution intact.\nexport const HIJAIYAH_AUDIO_CREDITS = ' + encoded + ' as const;\n')
    lines = [
        '# Hijaiyah recording attribution', '',
        'These 28 human recordings teach the names of Arabic letters. They are not a tajwid certification.', '',
        'Author: **Ruaa GHAREEB**, as credited on each Wikimedia Commons source page.',
        'License for the recordings and their converted MP3 versions: **[Creative Commons Attribution-ShareAlike 4.0 International](https://creativecommons.org/licenses/by-sa/4.0/)**.',
        'Changes: WAV converted to mono MP3 at 96 kbit/s. No speech synthesis or speech editing.',
        'This license applies to these recordings, not to the rest of the application code.', '',
        'Letter mapping follows [Wikiversity: Learn Arabic (Language Of Quran)/Alphabets](' + manifest['mappingSource'] + ').',
        'The manifest `credits.json` records original source SHA-1 and bundled MP3 SHA-256 hashes.', '',
        '| Letter | Bundled MP3 | Original recording |', '| --- | --- | --- |',
    ]
    for entry in manifest['entries']:
        lines.append(f"| {entry['letterId']} | {Path(entry['path']).name} | [{entry['sourceFile']}]({entry['sourceUrl']}) |")
    Path('public/assets/audio/hijaiyah/ATTRIBUTION.md').write_text('\n'.join(lines) + '\n')

def main():
    output = Path('public/assets/audio/hijaiyah')
    output.mkdir(parents=True, exist_ok=True)
    params = {'action': 'query', 'format': 'json', 'titles': '|'.join('File:' + filename for _, filename in FILES), 'prop': 'imageinfo', 'iiprop': 'url|extmetadata|sha1'}
    metadata = json.loads(fetch('https://commons.wikimedia.org/w/api.php?' + urllib.parse.urlencode(params)))
    pages = {p['title']: p for p in metadata['query']['pages'].values()}
    entries = []
    with tempfile.TemporaryDirectory() as temporary:
        for number, (slug, filename) in enumerate(FILES, 1):
            info = pages['File:' + filename]['imageinfo'][0]
            details = info['extmetadata']
            assert details['LicenseShortName']['value'] == 'CC BY-SA 4.0', filename
            target = output / f'{number:02}-{slug}.mp3'
            if not target.exists():
                original = fetch(info['url'])
                assert hashlib.sha1(original).hexdigest() == info['sha1'], filename
                source = Path(temporary) / 'source.wav'
                source.write_bytes(original)
                subprocess.run(['ffmpeg', '-v', 'error', '-y', '-i', str(source), '-ac', '1', '-codec:a', 'libmp3lame', '-b:a', '96k', str(target)], check=True)
                time.sleep(6.5)
            artist = re.sub('<[^>]+>', '', details['Artist']['value'])
            entries.append({'letterId': number, 'path': '/' + str(target.relative_to('public')), 'sourceFile': filename, 'sourceUrl': info['descriptionurl'], 'author': artist, 'license': 'CC BY-SA 4.0', 'licenseUrl': 'https://creativecommons.org/licenses/by-sa/4.0/', 'sourceSha1': info['sha1'], 'sha256': hashlib.sha256(target.read_bytes()).hexdigest(), 'changes': 'Converted from WAV to mono MP3 at 96 kbit/s; no speech synthesis.'})
            print(f'{number:02} {slug}: {target.stat().st_size} bytes; {artist}', flush=True)
    manifest = {'mappingSource': 'https://en.wikiversity.org/wiki/Learn_Arabic_(Language_Of_Quran)/Alphabets', 'recordingType': 'human', 'entries': entries}
    write_credits(manifest)

if __name__ == '__main__':
    main()
